def build(destination):
    patterns = {**UPPER, **LOWER, **SYMBOLS, **dict(zip('0123456789', DIGITS))}
    for letter in 'AaOoUu':
        rows=patterns[letter].split('/')
        if letter.islower(): rows[:2]=['01010','00000']
        else: rows=['01010','00000']+rows
        patterns[{'A':'Ä','a':'ä','O':'Ö','o':'ö','U':'Ü','u':'ü'}[letter]]='/'.join(rows)
    patterns['é']='00100/00010/'+LOWER['e'].split('/',2)[2]
    patterns['.notdef']='11111/10001/10101/10001/10101/10001/11111'
    glyphs={};metrics={};cmap={}
    for char,pattern in patterns.items():
        name='.notdef' if char=='.notdef' else 'uni'+format(ord(char),'04X')
        rows=pattern.split('/');width=max(map(len,rows));pen=TTGlyphPen(None)
        baseline=900 if char in 'ÄÖÜ' else 700
        for y,row in enumerate(rows):
            for x,pixel in enumerate(row):
                if pixel!='1':continue
                left=x*100;top=baseline-y*100
                pen.moveTo((left,top));pen.lineTo((left+100,top));pen.lineTo((left+100,top-100));pen.lineTo((left,top-100));pen.closePath()
        glyphs[name]=pen.glyph();metrics[name]=((width+1)*100,0)
        if char!='.notdef':cmap[ord(char)]=name
    font=FontBuilder(1000,isTTF=True);font.setupGlyphOrder(['.notdef']+sorted(n for n in glyphs if n!='.notdef'))
    font.setupCharacterMap(cmap);font.setupGlyf(glyphs);font.setupHorizontalMetrics(metrics)
    font.setupHorizontalHeader(ascent=900,descent=-200)
    font.setupNameTable({'familyName':'Plant Old School','styleName':'Regular','uniqueFontIdentifier':'PlantOldSchool-1','fullName':'Plant Old School Regular','psName':'PlantOldSchool-Regular','version':'Version 1.0','licenseDescription':'Original pixel glyphs created for Plant Monitor.'})
    font.setupOS2(sTypoAscender=900,sTypoDescender=-200,usWinAscent=900,usWinDescent=200)
    font.setupPost();font.setupMaxp();font.save(destination)


